export function getCropById(id: string): Crop | undefined {
  return CROPS.find((c) => c.id === id);
}

export function getCropsByCategory(): Record<string, Crop[]> {
  const result: Record<string, Crop[]> = {};
  for (const crop of CROPS) {
    if (!result[crop.category]) result[crop.category] = [];
    result[crop.category].push(crop);
  }
  return result;
}
