function plannerModesFor(type: CropType, category: CropCategory): PlannerMode[] {
  const modes: PlannerMode[] = ['beginner', 'advanced'];

  if (category === 'Fruit Trees' || category === 'Nut Trees' || category === 'Subtropical Fruits' || category === 'Tropical Fruits') {
    modes.push('orchard');
  }
  if (category === 'Food Forest Plants') {
    modes.push('food-forest');
  }
  if (type === 'perennial') {
    modes.push('perennial-planning');
  }
  if (category === 'Vegetables' || category === 'Herbs' || category === 'Berries' || category === 'Perennial Vegetables') {
    modes.push('family-food-security');
  }
  if (category === 'Vegetables' || category === 'Herbs' || category === 'Flowers' || category === 'Grains') {
    modes.push('market-garden');
  }

  return Array.from(new Set(modes));
}

function treesPerAcre(spacingFeet: number): number {
  return Math.round(43560 / (spacingFeet * spacingFeet));
}

function defineCrop(input: CropInput): Crop {
  return {
    ...input,
    daysToHarvest: input.daysToHarvest ?? input.daysToMaturity,
    perennial: input.perennial ?? input.type === 'perennial',
    plannerModes: input.plannerModes ?? plannerModesFor(input.type, input.category),
    squareFeetPerPlant: input.spacingSqFt,
    successionCapable: input.successionFriendly,
    yieldPerPlantLbs: input.yieldUnit === 'lbs' ? (input.yieldPerPlantLbs ?? input.yieldPerPlant) : input.yieldPerPlantLbs,
    yieldPerPlantUnits: input.yieldPerPlantUnits ?? input.yieldUnit,
  };
}

