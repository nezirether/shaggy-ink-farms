export function getCropById(id: string): Crop | undefined {
  return CROPS.find((crop) => crop.id === id);
}

export function getCropsByCategory(): Record<CropCategory, Crop[]> {
  return CATEGORY_ORDER.reduce((grouped, category) => {
    grouped[category] = CROPS.filter((crop) => crop.category === category);
    return grouped;
  }, {} as Record<CropCategory, Crop[]>);
}

export function filterCrops(filters: CropFilterState): Crop[] {
  const searchText = filters.search.trim().toLowerCase();

  return CROPS.filter((crop) => {
    const zoneMatch = filters.zone === 'All' || (crop.zoneMin <= filters.zone && crop.zoneMax >= filters.zone);
    const categoryMatch = filters.category === 'All' || crop.category === filters.category;
    const typeMatch = filters.type === 'All' || crop.type === filters.type;
    const seasonMatch =
      filters.season === 'all' ||
      (filters.season === 'hot' && crop.hotWeatherCrop) ||
      (filters.season === 'cool' && crop.coolWeatherCrop);
    const droughtMatch = !filters.droughtTolerantOnly || crop.droughtTolerant;
    const containerMatch = !filters.containerFriendlyOnly || crop.containerFriendly;
    const pollinatorMatch = !filters.pollinatorFriendlyOnly || crop.pollinatorFriendly;
    const familyMatch = !filters.familyFoodOnly || crop.familyFoodProduction;
    const marketMatch = !filters.marketGardenOnly || crop.marketGardenSuitable;
    const searchMatch =
      searchText === '' ||
      crop.name.toLowerCase().includes(searchText) ||
      crop.scientificName?.toLowerCase().includes(searchText) ||
      crop.subcategory?.toLowerCase().includes(searchText) ||
      crop.commonNames?.some((name) => name.toLowerCase().includes(searchText));

    return (
      zoneMatch &&
      categoryMatch &&
      typeMatch &&
      seasonMatch &&
      droughtMatch &&
      containerMatch &&
      pollinatorMatch &&
      familyMatch &&
      marketMatch &&
      searchMatch
    );
  });
}

